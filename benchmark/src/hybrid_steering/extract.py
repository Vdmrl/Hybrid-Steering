"""Create directions from model-generated neutral/target answer pairs.

Input: a folder with train.jsonl of unique {id, prompt} rows. Output:
train-answers.jsonl, directions.pt and source-manifest.json. The extraction
math stays in concept_comparison.prepare; existing verified pairs can be reused.
"""

import hashlib
import json
import os
import shutil
from pathlib import Path


from hybrid_steering.paths import ROOT


def conditioned_prompt(prompt: str, instruction: str | None) -> str:
    """Keep both members of a contrast pair on the same base prompt."""
    return prompt + ("\n\n" + instruction if instruction else "")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def training_prompts(folder: Path) -> list[dict]:
    """Read only fields used for extraction; fail on ambiguous IDs."""
    path = folder / "train.jsonl"
    with path.open(encoding="utf-8") as file:
        raw = [json.loads(line) for line in file if line.strip()]
    rows = []
    for row in raw:
        identifier, prompt = row["id"], row["prompt"]
        if type(identifier) not in (int, str) or not isinstance(prompt, str) or not prompt.strip():
            raise ValueError(f"Invalid training row in {path}")
        rows.append({"id": identifier, "prompt": prompt})
    if not rows or len({row["id"] for row in rows}) != len(rows):
        raise ValueError(f"Training prompts are empty or have duplicate IDs: {path}")
    return rows


def _check_saved_answers(path: Path, prompts: list[dict]) -> None:
    if not path.exists():
        return
    expected = {row["id"]: row["prompt"] for row in prompts}
    with path.open(encoding="utf-8") as file:
        saved = [json.loads(line) for line in file if line.strip()]
    ids = [row["id"] for row in saved]
    if (len(ids) != len(set(ids)) or len(saved) > len(prompts)
            or any(expected.get(row["id"]) != row["prompt"]
                   or not isinstance(row.get("neutral_response"), str)
                   or not isinstance(row.get("positive_response"), str) for row in saved)):
        raise ValueError(f"Saved training answers do not match prompts: {path}")


def _write_manifest(path: Path, value: dict) -> None:
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False), encoding="utf-8")
    temporary.replace(path)


def extract_directions(prompts_dir: Path, config_path: Path, output_dir: Path,
                       model=None, tokenizer=None, reuse_pairs: Path | None = None) -> Path:
    """Generate pairs as needed, extract directions and pin exact sources.

    `reuse_pairs` is an explicitly trusted, SHA256-pinned previous answer-pair
    file. Its prompt IDs and texts must match the current training prompts.
    The caller must also ensure it was generated by this model and instruction.
    """
    config = json.loads(config_path.read_text(encoding="utf-8"))
    prompts = training_prompts(prompts_dir)
    if len(prompts) != config["train_count"]:
        raise ValueError("train_count must equal the number of training prompts")
    if config.get("enable_thinking") is not False or config.get("system") is not None:
        raise ValueError("The shared extractor uses no-thinking and no system prompt")
    if (config.get("residual_representation") == "response_prefix"
            and config.get("residual_layers")
            and not 0 < config.get("residual_train_count", 0) <= len(prompts)):
        raise ValueError("response_prefix needs residual_train_count within training rows")
    if (model is None) != (tokenizer is None):
        raise ValueError("Pass both model and tokenizer, or neither")
    if reuse_pairs:
        expected = config.get("reuse_pairs_sha256")
        if not expected or sha256(reuse_pairs) != expected:
            raise ValueError("Reused training pairs need their exact SHA256 in the config")
        _check_saved_answers(reuse_pairs, prompts)
        with reuse_pairs.open(encoding="utf-8") as file:
            if sum(bool(line.strip()) for line in file) != len(prompts):
                raise ValueError("Reused training pairs must cover all prompts")

    if model is None:
        from hybrid_steering.language_benchmark import load_model
        placement = config.get("placement")
        if config.get("placement_config"):
            from hybrid_steering.paths import project_file
            placement_path = project_file(config["placement_config"])
            placement = json.loads(placement_path.read_text())["placement"]
        model, tokenizer = load_model(config["model"], placement)

    identity = {
        "concept": config["concept"], "model": config["model"],
        "model_revision": getattr(model.config, "_commit_hash", None),
        "tokenizer_revision": tokenizer.init_kwargs.get("_commit_hash"),
        "prompts_sha256": sha256(prompts_dir / "train.jsonl"),
        "config_sha256": sha256(config_path),
        "reused_pairs_sha256": config.get("reuse_pairs_sha256"),
        "code_sha256": {name: sha256(ROOT / name) for name in
                        ("src/hybrid_steering/comparison.py", "src/hybrid_steering/runner.py", "src/hybrid_steering/state.py")},
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = output_dir / "source-manifest.json"
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text(encoding="utf-8"))
        if previous["identity"] != identity:
            raise ValueError(f"Extraction source changed: {manifest_path}")
        if previous.get("directions_sha256") and sha256(output_dir / "directions.pt") != previous["directions_sha256"]:
            raise ValueError("Saved direction hash changed")
        if previous.get("answers_sha256") and sha256(output_dir / "train-answers.jsonl") != previous["answers_sha256"]:
            raise ValueError("Saved training-answer hash changed")
    elif (output_dir / "directions.pt").exists() or (output_dir / "train-answers.jsonl").exists():
        raise ValueError("Existing extraction files lack a source manifest")
    else:
        _write_manifest(manifest_path, {"identity": identity})

    pair_path = output_dir / "train-answers.jsonl"
    if reuse_pairs and not pair_path.exists():
        shutil.copyfile(reuse_pairs, pair_path)
    if config.get("seed_pairs") and not pair_path.exists():
        data_root = Path(os.environ["GDN_DATA_ROOT"]).resolve()
        seed = (data_root / config["seed_pairs"]).resolve()
        if not seed.is_relative_to(data_root) or sha256(seed) != config.get("seed_pairs_sha256"):
            raise ValueError("Seed pairs are outside data root or have changed")
        _check_saved_answers(seed, prompts)
        with seed.open(encoding="utf-8") as stream:
            seeded = [json.loads(line) for line in stream if line.strip()]
        if not 0 < len(seeded) < len(prompts) or any(not row["neutral_response"].strip()
                                                     or not row["positive_response"].strip()
                                                     for row in seeded):
            raise ValueError("Expected a nonempty proper subset of seed answer pairs")
        shutil.copyfile(seed, pair_path)
    _check_saved_answers(pair_path, prompts)
    from hybrid_steering.comparison import prepare
    prepare(model, tokenizer, prompts, config, output_dir)
    direction_path = output_dir / "directions.pt"
    _write_manifest(manifest_path, {
        "identity": identity,
        "answers_sha256": sha256(pair_path),
        "directions_sha256": sha256(direction_path),
    })
    return direction_path
